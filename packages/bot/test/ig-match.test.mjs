import test from "node:test";
import assert from "node:assert/strict";
import { подобрать, персональнаяМетка, подставить, норма } from "../src/ig/match.mjs";

// Порт lib/ig/match.test.mjs из исходного проекта — тот же набор пересечений
// (ДОДО внутри ДОДОИС, АКФИКС внутри «АКФИКС ИИ», короткий опасный ИИ с точным
// совпадением), логика match.mjs не менялась при переносе.
const СЦЕНАРИИ = [
  { ключ: "raketa", слова: ["ДОДО", "РАКЕТА"], совпадение: "вхождение", где: ["директ", "комментарий"] },
  { ключ: "dodois", слова: ["ДОДОИС"], совпадение: "вхождение", где: ["директ", "комментарий"] },
  { ключ: "akfix", слова: ["АКФИКС", "AKFIX"], совпадение: "вхождение", где: ["директ", "комментарий"] },
  { ключ: "akfix-ai", слова: ["АКФИКС ИИ"], совпадение: "вхождение", где: ["директ", "комментарий"] },
  { ключ: "ii", слова: ["ИИ"], совпадение: "точное", где: ["директ"] },
];

const ключ = (т, где) => подобрать(т, СЦЕНАРИИ, где)?.сценарий.ключ ?? null;

test("длинное слово побеждает короткое внутри себя", () => {
  assert.equal(ключ("ДОДОИС"), "dodois");
  assert.equal(ключ("додоис"), "dodois");
  assert.equal(ключ("ДОДО"), "raketa");
});

test("АКФИКС ИИ не уходит на АКФИКС", () => {
  assert.equal(ключ("АКФИКС ИИ"), "akfix-ai");
  assert.equal(ключ("акфикс"), "akfix");
  assert.equal(ключ("Хочу на АКФИКС ИИ, что по цене?"), "akfix-ai");
});

test("точное совпадение бьёт вхождение", () => {
  assert.equal(ключ("ИИ"), "ii");
  assert.equal(ключ("ии"), "ii");
});

test("короткий ключ не цепляет слова, где он лишь кусок", () => {
  assert.equal(ключ("это принципиально другой подход"), null);
  assert.equal(ключ("расскажите про риски"), null);
});

test("вхождение находится рядом со знаками препинания", () => {
  assert.equal(ключ("АКФИКС!"), "akfix");
  assert.equal(ключ("акфикс, привет"), "akfix");
  assert.equal(ключ("а что за «ракета»?"), "raketa");
});

test("вхождение не засчитывается внутри другого слова", () => {
  assert.equal(ключ("додокафе"), null);
  assert.equal(ключ("ЗАДОДОКАЛ"), null);
});

test("регистр и ё не мешают", () => {
  assert.equal(норма("АкФиКс  Ё"), "акфикс е");
  assert.equal(ключ("АкФиКс"), "akfix");
});

test("сценарий отвечает только там, где слушает", () => {
  assert.equal(ключ("ИИ", "директ"), "ii");
  assert.equal(ключ("ИИ", "комментарий"), null);
});

test("пустое и мусор не подбирают ничего", () => {
  assert.equal(ключ(""), null);
  assert.equal(ключ("   "), null);
  assert.equal(ключ("привет, как дела"), null);
  assert.equal(подобрать(null, СЦЕНАРИИ), null);
});

test("персональная метка несёт IGSID и чистит мусор", () => {
  assert.equal(персональнаяМетка("ig-akfix", "29245176808405808"), "ig-akfix-29245176808405808");
  assert.equal(персональнаяМетка("ig akfix!", "123"), "igakfix-123");
  assert.equal(персональнаяМетка("ig-akfix", ""), "ig-akfix");
  assert.ok(персональнаяМетка("ig-очень-длинная-метка".repeat(9), "29245176808405808").length <= 64);
});

test("плейсхолдеры заполняются, неизвестные остаются видимыми", () => {
  assert.equal(подставить("Практикум {дата}", { дата: "17 сентября" }), "Практикум 17 сентября");
  assert.equal(подставить("Цена {цена}", {}), "Цена {цена}");
  assert.equal(подставить("без плейсхолдеров", { дата: "1 мая" }), "без плейсхолдеров");
});

test("исключение вето́ит сценарий: «точка зрения» это не кодовое слово", () => {
  const сцен = [{
    ключ: "тур", слова: ["ТОЧКА", "ТОЧКУ"], где: ["комментарий"],
    исключения: ["точка зрения", "поставил точку"],
  }];
  assert.equal(подобрать("точка", сцен, "комментарий")?.сценарий.ключ, "тур");
  assert.equal(подобрать("напишу точку", сцен, "комментарий")?.сценарий.ключ, "тур");
  assert.equal(подобрать("точка зрения интересная", сцен, "комментарий"), null);
  assert.equal(подобрать("поставил точку в споре", сцен, "комментарий"), null);
  assert.equal(подобрать("карточка", сцен, "комментарий"), null);
});
