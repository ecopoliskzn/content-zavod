// Вход в бота по deep-link: t.me/<bot>?start=<метка> приходит как первое сообщение
// "/start <метка>". Порт lib/telegram/entry.ts из исходного проекта, упрощённый до
// generic-ядра: маршрутизация по конкретным площадкам/миссиям/событиям — дело
// сценариев и текстов конкретного инстанса бота (config), не этого пакета.
//
// Что сохранено из источника без изменения поведения:
//   - три формы, которыми приходит метка: "/start <метка>", "/start=<метка>" (человек
//     печатает хвост ссылки руками) и голое слово (площадка режет ссылку);
//   - голое слово принимается ТОЛЬКО если это известный материал (materialByEntry)
//     или совпадает с одним из configured-префиксов — иначе живая фраза из разговора
//     не должна разбираться как метка;
//   - отсечение персонального IGSID-хвоста ("ig-raketa-29245176808405808" → маршрут
//     "ig-raketa", но key остаётся полным — по нему считается атрибуция).
//
// Что НЕ портировано (кормишинские бизнес-ветки — miссии/wish/event/channel/radar):
// это работа сценариев инстанса, см. README пакета, "что осталось на потом".

/** Известные префиксы входа: канал-платформы + служебные метки. Настраивается конфигом. */
const ПРЕФИКСЫ_ПО_УМОЛЧАНИЮ = ["ig", "tt", "vk", "th", "li", "yt", "tc", "tg", "gr", "dm"];

/**
 * Суффиксы канала на конце метки ("<ключ материала>--site" → канал "site"): двойной дефис
 * не пересекается ни с персональным IGSID-хвостом (одиночный дефис + цифры), ни с ключами
 * материала на одиночном дефисе ("rol-hr"). Настраивается конфигом — новый канал = новая пара.
 */
const КАНАЛЫ_ПО_СУФФИКСУ_ПО_УМОЛЧАНИЮ = { "--site": "site", "--threads": "threads" };

/**
 * @param {string} text текст первого сообщения ("/start <метка>" или голое слово)
 * @param {object} [опции]
 * @param {(key: string) => ({key: string, intro?: string} | undefined)} [опции.materialByEntry]
 *   инстанс сообщает, есть ли материал, отдаваемый по этому ключу целиком (без разбора маршрута)
 * @param {string[]} [опции.платформы] список префиксов площадок, которые распознаются
 *   в голой (без "/start") форме и по которым строится "канал" для intro/учёта
 * @returns {{ key: string, material?: string, intro?: string, канал?: string } | null}
 */
export function parseEntry(text, опции = {}) {
  const {
    materialByEntry,
    платформы = ПРЕФИКСЫ_ПО_УМОЛЧАНИЮ,
    суффиксыКаналов = КАНАЛЫ_ПО_СУФФИКСУ_ПО_УМОЛЧАНИЮ,
  } = опции;

  const ПРЕФИКСЫ = new RegExp(`^(?:${платформы.join("|")})-[\\w-]+$|^(?:calendar|subscribe|direct|diag)$`, "i");
  const голая = String(text || "").trim();

  const материалКлюч = materialByEntry ? голая.toLowerCase() : null;
  const голыйМатериал = materialByEntry && !/[\s/]/.test(голая) && Boolean(materialByEntry(материалКлюч));

  const m = ПРЕФИКСЫ.test(голая) || голыйМатериал
    ? [null, голыйМатериал ? материалКлюч : голая]
    : голая.match(/^\/start(?:@\w+)?(?:[\s=]+(\S+))?$/i);
  if (!m) return null;

  const key = (m[1] || "").trim();
  if (!key) return { key: "direct" };

  // Хвост с IGSID отсекаем ДО маршрутизации: он мусор для маршрута, но key остаётся
  // полным ради атрибуции (см. ig/match.mjs → персональнаяМетка, который его туда кладёт).
  const маршрут = key.replace(/-\d{10,}$/, "");

  // Суффикс канала ("--site" и т.п.) режем ДО поиска материала — сам суффикс не часть
  // ключа материала, но полный key с суффиксом сохраняется в ответе (атрибуция/теги).
  let суффиксКанал;
  let ключБезСуффикса = key;
  for (const [суффикс, канал] of Object.entries(суффиксыКаналов)) {
    if (key.endsWith(суффикс)) {
      ключБезСуффикса = key.slice(0, -суффикс.length);
      суффиксКанал = канал;
      break;
    }
  }

  if (materialByEntry) {
    const material =
      materialByEntry(key) ||
      materialByEntry(маршрут) ||
      (суффиксКанал ? materialByEntry(ключБезСуффикса) : undefined);
    if (material) {
      return {
        key,
        material: material.key ?? material,
        intro: material.intro,
        ...(суффиксКанал ? { канал: суффиксКанал } : {}),
      };
    }
  }

  const dash = маршрут.indexOf("-");
  const канал = dash > 0 ? маршрут.slice(0, dash) : маршрут;
  if (платформы.includes(канал)) {
    return { key, канал };
  }

  return суффиксКанал ? { key, канал: суффиксКанал } : { key };
}

/** Ссылка для кнопки на сайте/в директе. */
export function botLink(botUsername, key) {
  return `https://t.me/${botUsername}?start=${encodeURIComponent(key)}`;
}
