/* Разбор входящего текста: какой сценарий отвечает.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Правило подбора обязано быть ОДНО на гейт и на рантайм.
 * Разъехавшись, они дают худший из возможных отказов: гейт зелёный, а живому человеку
 * уходит чужая карточка. По этой же причине один модуль на кнопку и на скрипт держат
 * подбор кадров в рилсах (lib/media/reel-pick.ts).
 *
 * ГЛАВНАЯ ЛОВУШКА — ВХОЖДЕНИЕ. Ключи пересекаются буквально: «ДОДО» (Ракета) целиком
 * содержится в «ДОДОИС», «АКФИКС» — в «АКФИКС ИИ». Человек, написавший ДОДОИС, при
 * наивном поиске по вхождению получит карточку Ракеты: короткое слово нашлось первым.
 * Поэтому порядок здесь не «как перечислено в папке», а осмысленный:
 *
 *   1. точное совпадение всей фразы бьёт любое вхождение;
 *   2. среди вхождений побеждает САМОЕ ДЛИННОЕ совпавшее слово;
 *   3. при равной длине — меньший «приоритет» (число), это ручной разрыв ничьей.
 *
 * Правило «длинное побеждает короткое» закрывает весь класс пересечений само, без
 * ручных приоритетов у каждой пары: ДОДОИС (6 знаков) выигрывает у ДОДО (4) всегда.
 *
 * ЧТО СЧИТАЕТСЯ СЛОВОМ. Регистр не важен, «ё» приравнена к «е» (люди пишут и так и так),
 * лишние пробелы схлопнуты. Знаки препинания вокруг слова не мешают: «АКФИКС!» и
 * «акфикс, привет» находятся. А вот внутрь другого слова вхождение не засчитывается —
 * иначе ключ ИИ срабатывал бы на «принципиально» и «риск», а это половина всех сообщений.
 */

/** Приводит текст к виду, в котором его сравнивают: регистр, ё, пробелы. */
export function норма(текст) {
  return String(текст || "")
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/\s+/g, " ")
    .trim();
}

/* Граница слова с поправкой на кириллицу: \b в JS работает по латинице и цифрам,
   на «АКФИКС.» он границу видит, а на «ИИ» внутри «принципиально» — тоже. Поэтому
   границу проверяем сами: слева и справа должно быть НЕ буквой и НЕ цифрой. */
const БУКВА = /[\p{L}\p{N}]/u;

/** Стоит ли слово в тексте отдельно (а не куском другого слова). */
function отдельноеСлово(текст, слово, откуда = 0) {
  const i = текст.indexOf(слово, откуда);
  if (i < 0) return false;
  const до = i > 0 ? текст[i - 1] : "";
  const после = i + слово.length < текст.length ? текст[i + слово.length] : "";
  if ((до && БУКВА.test(до)) || (после && БУКВА.test(после))) {
    // Нашли внутри другого слова — ищем дальше, вдруг есть отдельное вхождение.
    return отдельноеСлово(текст, слово, i + 1);
  }
  return true;
}

/**
 * Кто отвечает на этот текст.
 *
 * @param {string} текст  что написал человек
 * @param {Array}  сценарии  разобранные json-сценарии
 * @param {string} где  "директ" | "комментарий" — сценарий может слушать не везде
 * @returns {{сценарий: object, слово: string, вид: "точное"|"вхождение"}|null}
 */
export function подобрать(текст, сценарии, где = "директ") {
  const т = норма(текст);
  if (!т) return null;

  const кандидаты = [];
  for (const с of сценарии) {
    if (где && Array.isArray(с.где) && !с.где.includes(где)) continue;

    /* Исключения: обороты, в которых ключевое слово живёт своей жизнью и к нам
       отношения не имеет. Понадобились 09.09.2026, когда в сценарий тура добавили
       слово ТОЧКА под рилс: границы слова движок считает верно, «карточка» и
       «минуточка» не срабатывают, — а вот «точка зрения» и «поставил точку» это
       нормальные обороты под деловым роликом, и авто-ответ на них читается как бот.
       Исключение вето́ит весь сценарий для этого текста, а не одно слово: человек,
       написавший «точка зрения», не ждёт от нас ничего. */
    const исключено = (с.исключения || []).some((ф) => {
      const н = норма(ф);
      return н && т.includes(н);
    });
    if (исключено) continue;


    /* Сценарий-шаблон ловит не слово, а форму: «мне 45», «45 лет». Список слов тут
       бесполезен, значений сотни. Из совпадения достаём число и кладём в «слово» —
       дальше движок работает с ним так же, как со знаком зодиака. */
    if (с.шаблон) {
      const м = т.match(new RegExp(с.шаблон, "i"));
      const значение = м ? (м.slice(1).find(Boolean) ?? м[0]) : null;
      if (значение) кандидаты.push({ сценарий: с, слово: значение, вид: "шаблон", длина: 0 });
      continue;
    }
    for (const слово of с.слова || []) {
      const сл = норма(слово);
      if (!сл) continue;
      if (т === сл) {
        кандидаты.push({ сценарий: с, слово, вид: "точное", длина: сл.length });
        continue;
      }
      /* Сценарий с «совпадение»: «точное» ловит только всю фразу целиком: так живут
         короткие и опасные ключи вроде ИИ, которые иначе цепляли бы полтекста. */
      if (с.совпадение === "точное") continue;
      if (отдельноеСлово(т, сл)) {
        кандидаты.push({ сценарий: с, слово, вид: "вхождение", длина: сл.length });
      }
    }
  }
  if (!кандидаты.length) return null;

  const весВида = { точное: 0, вхождение: 1, шаблон: 2 };
  кандидаты.sort((a, b) => {
    /* 1. Точное бьёт вхождение, вхождение бьёт шаблон. Шаблон самый широкий: он ловит
       форму, а не конкретное слово, и обязан уступать всякому, кто узнал ключ точно.
       Иначе «мне 45, еду на АКФИКС» уйдёт в возрастной сценарий вместо программы. */
    if (a.вид !== b.вид) return весВида[a.вид] - весВида[b.вид];
    // 2. длинное слово бьёт короткое: ДОДОИС побеждает ДОДО
    if (a.длина !== b.длина) return b.длина - a.длина;
    // 3. ручной разрыв ничьей
    const па = a.сценарий.приоритет ?? 100;
    const пб = b.сценарий.приоритет ?? 100;
    if (па !== пб) return па - пб;
    return String(a.сценарий.ключ).localeCompare(String(b.сценарий.ключ));
  });

  const { сценарий, слово, вид } = кандидаты[0];
  return { сценарий, слово, вид };
}

/**
 * Персональная метка входа в бота: она же склейка инстаграм- и телеграм-записей.
 * Общая метка отвечает на вопрос «сколько людей пришло», персональная — «кто именно»,
 * а без этого две базы не сходятся ни по одному полю (ТЗ, пункт 1 критики).
 *
 * Телеграм принимает в start до 64 знаков и только [A-Za-z0-9_-]; IGSID — 17 цифр,
 * помещается с большим запасом. Длину всё равно режем: метка сценария правится руками.
 */
export function персональнаяМетка(метка, igsid) {
  const чистая = String(метка || "").replace(/[^A-Za-z0-9_-]/g, "");
  const id = String(igsid || "").replace(/\D/g, "");
  if (!id) return чистая;
  return `${чистая}-${id}`.slice(0, 64);
}

/**
 * Подставляет в текст живые значения календаря.
 * Даты берём в рантайме, а не при сборке: на VPS data/missions.json перезаписывается
 * деплоем, и текст, собранный однажды, зовёт на прошедшее (D-037).
 */
export function подставить(текст, значения = {}) {
  return String(текст || "").replace(/\{([а-яёa-z]+)\}/gi, (весь, имя) => {
    const з = значения[имя];
    return з === undefined || з === null ? весь : String(з);
  });
}
