# Content factory: scheduled tasks on the operator PC (schedule mirror, watchdog, vault).
#
# Run once from the project root:
#   powershell -ExecutionPolicy Bypass -File ops\windows\install-tasks.ps1
# Remove the tasks:
#   powershell -ExecutionPolicy Bypass -File ops\windows\install-tasks.ps1 -Remove
#
# This file is ASCII only on purpose: Windows PowerShell 5.1 reads a .ps1 without BOM in
# the ANSI code page and breaks Cyrillic. The Russian description is in ops\windows\README.md.
#
# The wrappers (*.cmd) are generated here with the ABSOLUTE path to node.exe: Task Scheduler
# starts tasks with its own PATH, and a bare "node" silently fails there.

param([switch]$Remove)

$ErrorActionPreference = "Stop"
$root = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path
$tasks = @("zavod-mirror", "zavod-vault", "zavod-takeover")

if ($Remove) {
  foreach ($t in $tasks) {
    try { Unregister-ScheduledTask -TaskName $t -Confirm:$false -ErrorAction Stop; Write-Host "removed: $t" } catch { Write-Host "not found: $t" }
  }
  exit 0
}

$node = (Get-Command node -ErrorAction Stop).Source
$logDir = Join-Path $root "mirror"
New-Item -ItemType Directory -Force -Path $logDir | Out-Null

function New-Wrapper([string]$name, [string]$script, [string]$scriptArgs) {
  $file = Join-Path $PSScriptRoot "$name.cmd"
  $lines = @(
    "@echo off",
    "rem generated by install-tasks.ps1 - do not edit, run the installer again instead",
    "cd /d `"$root`"",
    "`"$node`" $script $scriptArgs >> `"$logDir\$name.log`" 2>&1"
  )
  Set-Content -Path $file -Value $lines -Encoding ASCII
  return $file
}

function Register-Zavod([string]$name, [string]$file, $trigger, [bool]$enabled) {
  $action = New-ScheduledTaskAction -Execute $file -WorkingDirectory $root
  $settings = New-ScheduledTaskSettingsSet -StartWhenAvailable -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Minutes 30)
  Register-ScheduledTask -TaskName $name -Action $action -Trigger $trigger -Settings $settings -Force | Out-Null
  if (-not $enabled) { Disable-ScheduledTask -TaskName $name | Out-Null }
  $state = "enabled"
  if (-not $enabled) { $state = "DISABLED (emergency only)" }
  Write-Host "registered: $name - $state"
}

$every15 = New-ScheduledTaskTrigger -Once -At (Get-Date).Date -RepetitionInterval (New-TimeSpan -Minutes 15) -RepetitionDuration (New-TimeSpan -Days 3650)
$every5 = New-ScheduledTaskTrigger -Once -At (Get-Date).Date -RepetitionInterval (New-TimeSpan -Minutes 5) -RepetitionDuration (New-TimeSpan -Days 3650)
$daily = New-ScheduledTaskTrigger -Daily -At "08:15"

$mirror = New-Wrapper "mirror" "src\queue\mirror.mjs" "--watch"
$vault = New-Wrapper "vault" "src\vault\build.mjs" ""
$takeover = New-Wrapper "takeover" "src\queue\runner.mjs" ""

Register-Zavod "zavod-mirror" $mirror $every15 $true
Register-Zavod "zavod-vault" $vault $daily $true
Register-Zavod "zavod-takeover" $takeover $every5 $false

Write-Host ""
Write-Host "node: $node"
Write-Host "logs: $logDir\mirror.log, vault.log, takeover.log"
Write-Host "zavod-takeover stays disabled. Enable it only after: npm run mirror -- --takeover --yes"
