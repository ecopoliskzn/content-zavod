// Дзен: программной публикации нет. Статья выходит пакетом на ручную выкладку.
//
// СТАТУС: проверено по справке Дзена на 10.10.2026. Открытого API у площадки нет.
// Автоматически в Дзен попадает только то, что транслируется:
//   · из публичного Telegram-канала через официального бота Дзена (в Студии берётся
//     код, боту отправляется команда /sync, бот добавляется администратором канала).
//     Заголовок до 140 знаков, вложение до 20 МБ, разметка теряется;
//   · из ленты RSS своего сайта. Домен ленты обязан совпадать с доменом сайта, а сайт
//     клиента ведёт другой подрядчик: для завода этот путь закрыт.
// Поэтому у Дзена два потока. Посты Telegram-канала попадают туда сами, без участия
// завода (настраивается один раз в сессии S1). А статьи, написанные для Дзена отдельно
// (длинные, с прямым предложением: площадка открытая), выходят этим файлом — пакетом.
//
// Цифры Дзен отдаёт только в Студии: программно их не снять. В отчёт они попадают,
// если сотрудник раз в неделю присылает в группу просмотры статьи.

import { sendPackage } from "./manual.mjs";

export const name = "dzen";

export async function publish(entry, ctx = {}) {
  return sendPackage(entry, {
    onState: ctx.onState,
    why: "У Дзена нет программной публикации: статью вставляет человек.",
    steps: [
      "Откройте Студию Дзена: dzen.ru/profile/editor и нажмите «Создать → Статья».",
      "Вставьте заголовок и текст из следующего сообщения.",
      "Поставьте обложку: файл по ссылке ниже, если она есть.",
      "Проверьте, что абзацы и подзаголовки на месте, и нажмите «Опубликовать».",
      "Вернитесь сюда: нажмите «Выложено» и ответьте на это сообщение ссылкой на статью.",
    ],
  });
}

/** Для doctor: проверять нечего, площадка без ключа. */
export async function probe() {
  return { kind: "ok", detail: "ручная выкладка по пакету из группы; трансляция постов из Telegram настраивается в Студии Дзена" };
}
